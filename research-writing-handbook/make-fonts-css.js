#!/usr/bin/env node
/**
 * Generates assets/fonts.css with DejaVu Sans and DejaVu Sans Mono embedded as
 * base64 @font-face rules.
 *
 * Why: the handbook's 30 figures are ASCII-art diagrams using box-drawing and
 * arrow characters (U+2500 range, U+2190 range), and the checklists use ballot
 * boxes (U+2610). Common system fonts — including the Noto Sans that many
 * minimal Linux images default to — do not cover these ranges, so the glyphs
 * render as empty boxes. Embedding the fonts makes the PDF build reproducible
 * on any machine without requiring a font install.
 *
 * Usage:  node make-fonts-css.js [/path/to/DejaVuSans.ttf /path/to/DejaVuSansMono.ttf]
 * Defaults to the standard Linux locations.
 */
const fs = require('fs');
const path = require('path');

const DEFAULTS = [
  ['DejaVu Sans', '/usr/share/fonts/dejavu-sans-fonts/DejaVuSans.ttf', 400, 'normal'],
  ['DejaVu Sans', '/usr/share/fonts/dejavu-sans-fonts/DejaVuSans-Bold.ttf', 700, 'normal'],
  ['DejaVu Sans', '/usr/share/fonts/dejavu-sans-fonts/DejaVuSans-Oblique.ttf', 400, 'italic'],
  ['DejaVu Sans Mono', '/usr/share/fonts/dejavu-sans-mono-fonts/DejaVuSansMono.ttf', 400, 'normal'],
  ['DejaVu Sans Mono', '/usr/share/fonts/dejavu-sans-mono-fonts/DejaVuSansMono-Bold.ttf', 700, 'normal'],
];

let css =
  '/* Auto-generated by make-fonts-css.js — do not edit by hand.\n' +
  '   DejaVu fonts embedded so box-drawing, arrow, and ballot-box glyphs in the\n' +
  '   diagrams and checklists render on any machine. DejaVu is licensed under a\n' +
  '   permissive free licence (Bitstream Vera derivative). */\n\n';

let embedded = 0;
for (const [family, file, weight, style] of DEFAULTS) {
  if (!fs.existsSync(file)) {
    console.warn(`  skip (not found): ${file}`);
    continue;
  }
  const b64 = fs.readFileSync(file).toString('base64');
  css +=
    `@font-face{font-family:"${family}";font-weight:${weight};font-style:${style};` +
    `font-display:block;src:url(data:font/ttf;base64,${b64}) format("truetype");}\n\n`;
  embedded++;
  console.log(`  embedded: ${path.basename(file)} (${family} ${weight} ${style})`);
}

if (!embedded) {
  console.error('No DejaVu fonts found. Install dejavu-sans-fonts and dejavu-sans-mono-fonts.');
  process.exit(1);
}

fs.mkdirSync(path.join(__dirname, 'assets'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'assets', 'fonts.css'), css);
console.log(`  wrote assets/fonts.css (${(css.length / 1048576).toFixed(1)} MB, ${embedded} faces)`);
